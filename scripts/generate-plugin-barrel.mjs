// Regenerates src/widgets/plugins-generated.ts -- the static barrel of built-in
// widget plugins. Built-in plugins must be imported statically (not via
// require.context) so their definitions resolve synchronously: webpack treats them
// as async modules (they import proxy handlers), and require.context returns
// Promises for async modules, which getPluginDefinitions cannot use.
//
// Run automatically via the predev/prebuild scripts and by scripts/create-widget.ts.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PLUGINS_DIR = path.join(__dirname, "..", "src", "widgets", "plugins");
const OUTPUT = path.join(__dirname, "..", "src", "widgets", "plugins-generated.ts");

function toIdentifier(dirName) {
  const camel = dirName.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase()).replace(/[^a-zA-Z0-9_$]/g, "");
  return /^[a-zA-Z_$]/.test(camel) ? camel : `_${camel}`;
}

function hasIndex(dir) {
  return ["index.ts", "index.js", "index.tsx", "index.jsx"].some((f) => fs.existsSync(path.join(dir, f)));
}

const dirs = fs.existsSync(PLUGINS_DIR)
  ? fs
      .readdirSync(PLUGINS_DIR, { withFileTypes: true })
      .filter((e) => e.isDirectory() && hasIndex(path.join(PLUGINS_DIR, e.name)))
      .map((e) => e.name)
      .sort()
  : [];

// Guard against identifier collisions after sanitizing hyphens etc.
const seen = new Map();
const entries = dirs.map((dir) => {
  let id = toIdentifier(dir);
  while (seen.has(id)) id = `${id}_`;
  seen.set(id, dir);
  return { dir, id };
});

const header =
  "// AUTO-GENERATED by scripts/generate-plugin-barrel.mjs -- do not edit by hand.\n" +
  "// Built-in widget plugins, imported statically so their definitions resolve\n" +
  "// synchronously (require.context returns Promises for these async modules).\n";

const imports = entries.map(({ dir, id }) => `import ${id} from "./plugins/${dir}";`).join("\n");

const arrayBody = entries.map(({ dir, id }) => `  { dir: "${dir}", widget: ${id} },`).join("\n");

const contents =
  `${header}` +
  (imports ? `${imports}\n\n` : "\n") +
  `const builtinPlugins: { dir: string; widget: unknown }[] = [\n` +
  (arrayBody ? `${arrayBody}\n` : "") +
  `];\n\n` +
  `export default builtinPlugins;\n`;

fs.writeFileSync(OUTPUT, contents);
console.log(
  `generate-plugin-barrel: wrote ${entries.length} built-in plugin(s) to ${path.relative(process.cwd(), OUTPUT)}`,
);
